// Case-insensitive normalized lookup
const NORMALIZED_DICT: Record<'hi' | 'te' | 'mr', Record<string, string>> = {
  hi: {},
  te: {},
  mr: {}
};

for (const lang of ['hi', 'te', 'mr'] as const) {
  for (const [k, v] of Object.entries(MASTER_DICTIONARY[lang])) {
    NORMALIZED_DICT[lang][k.trim().toLowerCase()] = v;
  }
}

/**
 * Universal instant 0ms in-memory translator
 * Returns localized string for any key, phrase, crop name, unit, or category.
 */
export function tr(text: string, lang: LanguageCode): string {
  if (!text || lang === 'en') return text;
  const trimmed = text.trim();

  // 1. Direct key match in translations[lang]
  if (translations[lang] && translations[lang][trimmed]) {
    return translations[lang][trimmed];
  }

  // 2. Direct match in MASTER_DICTIONARY
  const langKey = lang as 'hi' | 'te' | 'mr';
  if (MASTER_DICTIONARY[langKey] && MASTER_DICTIONARY[langKey][trimmed]) {
    return MASTER_DICTIONARY[langKey][trimmed];
  }

  // 3. Normalized lowercase match in MASTER_DICTIONARY
  const lower = trimmed.toLowerCase();
  if (NORMALIZED_DICT[langKey] && NORMALIZED_DICT[langKey][lower]) {
    return NORMALIZED_DICT[langKey][lower];
  }

  // 4. Crop name match
  if (CROP_TRANSLATIONS[langKey] && CROP_TRANSLATIONS[langKey][trimmed]) {
    return CROP_TRANSLATIONS[langKey][trimmed];
  }

  // 5. Unit translation
  const unitRes = translateUnit(trimmed, lang);
  if (unitRes !== trimmed) return unitRes;

  return text;
}

export function translateCrop(cropName: string, lang: LanguageCode): string {
  if (!cropName || lang === 'en' || !['hi', 'te', 'mr'].includes(lang)) return cropName;
  const map = CROP_TRANSLATIONS[lang as 'hi' | 'te' | 'mr'];
  return map[cropName] || cropName;
}

export function translateUnit(unit: string, lang: LanguageCode): string {
  if (!unit || lang === 'en') return unit;
  const u = unit.toLowerCase();
  if (u.includes('quintal')) {
    if (lang === 'hi') return 'क्विंटल';
    if (lang === 'te') return 'క్వింటాల్';
    if (lang === 'mr') return 'क्विंटल';
  }
  if (u === 'kg' || u.includes('kg') || u.includes('kilo')) {
    if (lang === 'hi') return 'किलो';
    if (lang === 'te') return 'కిలో';
    if (lang === 'mr') return 'किलो';
  }
  if (u.includes('tonne') || u.includes('ton')) {
    if (lang === 'hi') return 'टन';
    if (lang === 'te') return 'టన్ను';
    if (lang === 'mr') return 'टन';
  }
  return unit;
}

export function translateCategory(cat: string, lang: LanguageCode): string {
  if (!cat || lang === 'en') return cat;
  return tr(cat, lang);
}
