export function translateCrop(cropName: string, lang: LanguageCode): string {
  if (!cropName || lang === 'en' || !['hi', 'te', 'mr'].includes(lang)) return cropName;
  const map = CROP_TRANSLATIONS[lang as 'hi' | 'te' | 'mr'];
  return map[cropName] || cropName;
}

export function translateUnit(unit: string, lang: LanguageCode): string {
  if (lang === 'en') return unit;
  if (unit.toLowerCase().includes('quintal')) {
    if (lang === 'hi') return 'क्विंटल';
    if (lang === 'te') return 'క్వింటాల్';
    if (lang === 'mr') return 'क्विंटल';
  }
  if (unit.toLowerCase() === 'kg' || unit.toLowerCase().includes('kg')) {
    if (lang === 'hi') return 'किलो';
    if (lang === 'te') return 'కిలో';
    if (lang === 'mr') return 'किलो';
  }
  if (unit.toLowerCase().includes('tonne') || unit.toLowerCase().includes('ton')) {
    if (lang === 'hi') return 'टन';
    if (lang === 'te') return 'టన్ను';
    if (lang === 'mr') return 'टन';
  }
  return unit;
}
